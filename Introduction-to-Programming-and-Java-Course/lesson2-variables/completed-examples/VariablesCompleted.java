public class VariablesCompleted {
    public static void main(String[] args) {

        // Variable entera — números sin decimales
        int edad = 15;

        // Variable de texto — siempre entre comillas
        String nombre = "Ana";

        // Variable decimal — para precios o medidas
        double precio = 25.90;

        // Variable booleana — solo true o false
        boolean meGustaJava = true;

        // Mostramos todo en pantalla
        System.out.println("Nombre: " + nombre);
        System.out.println("Edad: " + edad);
        System.out.println("Precio favorito: S/." + precio);
        System.out.println("¿Le gusta Java?: " + meGustaJava);
    }
}